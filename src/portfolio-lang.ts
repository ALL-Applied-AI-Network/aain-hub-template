const BY_LOWER = new Map(Object.entries(LANGUAGE_COLORS).map(([k, v]) => [k.toLowerCase(), v]));

/** The linguist colour for a repo's language, or null when GitHub has
 *  none we carry. Case-insensitive: the API sends "Jupyter Notebook",
 *  a hand-typed fixture might not. */
export function languageColor(language: string | null | undefined): string | null {
  const key = (language ?? "").trim().toLowerCase();
  return key ? BY_LOWER.get(key) ?? null : null;
}
