export function renderBadgeIcon(icon: string): string {
  const key = (icon ?? "").trim();
  if (
    key.startsWith("http://") ||
    key.startsWith("https://") ||
    key.startsWith("data:image/")
  ) {
    return `<img src="${escapeAttr(key)}" alt="" />`;
  }
  return BUILT_IN_ICONS[key] ?? BUILT_IN_ICONS.trophy;
}
